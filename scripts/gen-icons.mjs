/* Generates components/icons.js (React SVG elements) from the legacy icon sets I, TI, RI.
   Run: node scripts/gen-icons.mjs   (needs the backend running for the legacy loader) */
import fs from 'node:fs';
import { parse } from 'node-html-parser';
import { loadLegacy } from './fidelity/legacy.mjs';

const { X } = await loadLegacy(['I', 'TI', 'RI']);
const CAMEL = a => (a === 'class' ? 'className' : a === 'xlink:href' ? 'xlinkHref' : a.includes('-') && !a.startsWith('data-') && !a.startsWith('aria-') ? a.replace(/-([a-z])/g, (m, c) => c.toUpperCase()) : a);
const q = v => JSON.stringify(v);
function jsx(node, ind) {
  if (node.nodeType === 3) { const t = node.rawText; return t.trim() ? `{${q(t)}}` : ''; }
  const attrs = Object.entries(node.attributes).map(([k, v]) => `${CAMEL(k)}=${q(v)}`).join(' ');
  const kids = node.childNodes.map(c => jsx(c, ind + '  ')).filter(Boolean);
  const tag = node.rawTagName;
  return kids.length ? `<${tag}${attrs ? ' ' + attrs : ''}>${kids.join('')}</${tag}>` : `<${tag}${attrs ? ' ' + attrs : ''} />`;
}
const set = (name, obj) => `export const ${name} = {\n${Object.entries(obj).map(([k, svg]) => {
  const root = parse(svg, { lowerCaseTagName: false });
  const els = root.childNodes.filter(n => n.nodeType === 1);
  if (els.length !== 1) throw new Error(`${name}.${k}: expected one root element`);
  return `  ${q(k)}: ${jsx(els[0], '  ')},`;
}).join('\n')}\n};\n`;

const out = `/* Generated by scripts/gen-icons.mjs from the original website icons — do not edit by hand.
   I: UI icons · TI: theme icons · RI: illustration icons. Each value is a React element; use withProps() to add size etc. */
import { cloneElement } from 'react';

${set('I', X.I)}
${set('TI', X.TI)}
${set('RI', X.RI)}
/* e.g. withProps(I.chev, { width: 14, height: 14 }) */
export const withProps = (el, props) => cloneElement(el, props);
`;
fs.writeFileSync(new URL('../components/icons.js', import.meta.url), out);
console.log('icons:', Object.keys(X.I).length, 'I,', Object.keys(X.TI).length, 'TI,', Object.keys(X.RI).length, 'RI');
